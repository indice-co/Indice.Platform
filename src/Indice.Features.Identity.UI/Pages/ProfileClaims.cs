#if NET9_0_OR_GREATER
using Duende.IdentityModel;
#else
using IdentityModel;
#endif
using System.Globalization;
using System.Security.Claims;
using System.Text.RegularExpressions;
using Indice.Features.Identity.Core.Data;
using Indice.Features.Identity.Core.Data.Models;
using Indice.Features.Identity.UI.Models;
using Indice.Security;
using Microsoft.EntityFrameworkCore;

namespace Indice.Features.Identity.UI.Pages;

/// <summary>Helpers for the user editable claims shown on the profile pages.</summary>
internal static class ProfileClaims
{
    internal const string DateFormat = "yyyy-MM-dd";
    private static readonly TimeSpan RuleTimeout = TimeSpan.FromMilliseconds(250);

    // Claim types that have a dedicated field or page, or that must never be edited as a plain value.
    private static readonly HashSet<string> ManagedClaimTypes = new(StringComparer.Ordinal) {
        JwtClaimTypes.GivenName,
        JwtClaimTypes.FamilyName,
        BasicClaimTypes.Tin,
        JwtClaimTypes.BirthDate,
        JwtClaimTypes.ZoneInfo,
        JwtClaimTypes.Locale,
        BasicClaimTypes.ConsentCommercial,
        BasicClaimTypes.ConsentCommercialDate,
        BasicClaimTypes.DeveloperTotp,
        JwtClaimTypes.Email,
        JwtClaimTypes.EmailVerified,
        JwtClaimTypes.PhoneNumber,
        JwtClaimTypes.PhoneNumberVerified,
        JwtClaimTypes.Name,
        JwtClaimTypes.PreferredUserName,
        JwtClaimTypes.Picture,
        JwtClaimTypes.Subject,
        JwtClaimTypes.Role
    };

    /// <summary>Gets all the claim types that are marked as user editable.</summary>
    public static Task<List<ClaimType>> GetUserEditableClaimTypesAsync(ExtendedConfigurationDbContext configurationDbContext) =>
        configurationDbContext.ClaimTypes.AsNoTracking().Where(x => x.UserEditable).ToListAsync();

    /// <summary>Builds the additional user editable claims (those without a dedicated field or page) with the user's current values.</summary>
    public static List<ProfileClaimViewModel> GetAdditionalClaims(IEnumerable<ClaimType> userEditableClaimTypes, IEnumerable<Claim> userClaims) =>
        userEditableClaimTypes
            .Where(x => x.UserEditable && !x.AutoGenerated && !ManagedClaimTypes.Contains(x.Name))
            .OrderBy(x => string.IsNullOrWhiteSpace(x.DisplayName) ? x.Name : x.DisplayName, StringComparer.CurrentCultureIgnoreCase)
            .Select(x => new ProfileClaimViewModel {
                Type = x.Name,
                DisplayName = string.IsNullOrWhiteSpace(x.DisplayName) ? x.Name : x.DisplayName,
                Description = x.Description,
                ValueType = x.ValueType,
                Required = x.Required,
                Rule = x.Rule,
                Value = FormatForInput(x.ValueType, userClaims.FirstOrDefault(claim => claim.Type == x.Name)?.Value)
            })
            .ToList();

    /// <summary>Formats a stored claim value so that it can be used as the value of an HTML input.</summary>
    public static string? FormatForInput(ClaimValueType valueType, string? value) {
        if (string.IsNullOrWhiteSpace(value)) {
            return null;
        }
        return valueType switch {
            ClaimValueType.Boolean => bool.TryParse(value, out var boolean) ? (boolean ? "true" : "false") : value,
            ClaimValueType.DateTime => TryParseDate(value, out var date) ? date.ToString(DateFormat, CultureInfo.InvariantCulture) : value,
            _ => value
        };
    }

    /// <summary>Determines whether the posted value is different from the current value.</summary>
    public static bool HasChanged(ProfileClaimViewModel claim, string? postedValue) {
        if (claim.ValueType == ClaimValueType.Boolean) {
            return IsTrue(claim.Value) != IsTrue(postedValue);
        }
        return !string.Equals(claim.Value ?? string.Empty, postedValue?.Trim() ?? string.Empty, StringComparison.Ordinal);
    }

    /// <summary>Validates the posted value of a claim and converts it to the format it is stored in.</summary>
    /// <returns><see langword="null"/> when the value is valid, otherwise the error kind.</returns>
    public static ProfileClaimError? TryNormalize(ProfileClaimViewModel claim, string? postedValue, out string normalizedValue) {
        normalizedValue = postedValue?.Trim() ?? string.Empty;
        if (claim.ValueType == ClaimValueType.Boolean) {
            normalizedValue = IsTrue(normalizedValue) ? "true" : "false";
            return null;
        }
        if (normalizedValue.Length == 0) {
            return claim.Required ? ProfileClaimError.Required : null;
        }
        switch (claim.ValueType) {
            case ClaimValueType.Int:
                if (!int.TryParse(normalizedValue, NumberStyles.Integer, CultureInfo.InvariantCulture, out var number)) {
                    return ProfileClaimError.Invalid;
                }
                normalizedValue = number.ToString(CultureInfo.InvariantCulture);
                break;
            case ClaimValueType.DateTime:
                if (!TryParseDate(normalizedValue, out var date)) {
                    return ProfileClaimError.Invalid;
                }
                normalizedValue = date.ToString(DateFormat, CultureInfo.InvariantCulture);
                break;
        }
        return string.IsNullOrWhiteSpace(claim.Rule) || MatchesRule(claim.Rule, normalizedValue) ? null : ProfileClaimError.Invalid;
    }

    private static bool IsTrue(string? value) => bool.TryParse(value, out var boolean) && boolean;

    private static bool TryParseDate(string value, out DateTime date) =>
        DateTime.TryParseExact(value, DateFormat, CultureInfo.InvariantCulture, DateTimeStyles.None, out date) ||
        DateTime.TryParse(value, CultureInfo.InvariantCulture, DateTimeStyles.RoundtripKind, out date);

    // The rule must match the whole value, the same way an HTML pattern attribute does. Broken rules fail closed.
    private static bool MatchesRule(string rule, string value) {
        try {
            return Regex.IsMatch(value, $"^(?:{rule})$", RegexOptions.CultureInvariant, RuleTimeout);
        } catch (ArgumentException) {
            return false;
        } catch (RegexMatchTimeoutException) {
            return false;
        }
    }
}

/// <summary>The kind of validation error of a user editable claim value.</summary>
internal enum ProfileClaimError
{
    Required,
    Invalid
}
