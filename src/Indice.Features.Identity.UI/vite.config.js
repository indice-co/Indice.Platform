const stripComments = (contents) => contents.toString().replace(/\/\*[\s\S]*?\*\/|^\s*\/\/.*/gm, '');

/**
 * Builds wwwroot/lib/lucide/sprite.svg, a curated Lucide sprite consumed by the <icon name="..." /> tag helper.
 * Icons are collected from literal <icon name="..."> usages in Razor views and from the string literals of
 * IdentityUIIcons.cs (dynamic icons). Unknown icon names fail the build.
 */
function lucideSprite() {
    const iconsDir = path.resolve(__dirname, 'node_modules/lucide-static/icons');
    const output = path.resolve(__dirname, 'wwwroot/lib/lucide/sprite.svg');
    const collect = () => {
        const names = new Set();
        const missing = [];
        for (const file of globSync('./Pages/**/*.cshtml', { cwd: __dirname })) {
            const contents = fs.readFileSync(path.resolve(__dirname, file), 'utf8');
            for (const match of contents.matchAll(/<icon\b[^>]*?\sname="([^"@]+)"/g)) {
                if (fs.existsSync(path.join(iconsDir, `${match[1]}.svg`))) {
                    names.add(match[1]);
                } else {
                    missing.push(`${match[1]} (${file})`);
                }
            }
        }
        const helper = fs.readFileSync(path.resolve(__dirname, 'IdentityUIIcons.cs'), 'utf8');
        for (const match of helper.matchAll(/"([a-z0-9-]+)"/g)) {
            if (fs.existsSync(path.join(iconsDir, `${match[1]}.svg`))) {
                names.add(match[1]);
            }
        }
        if (missing.length) {
            throw new Error(`Unknown Lucide icon(s): ${missing.join(', ')}. See https://lucide.dev/icons.`);
        }
        return [...names].sort();
    };
    return {
        name: 'lucide-sprite',
        buildStart() {
            const symbols = collect().map(name => {
                const svg = fs.readFileSync(path.join(iconsDir, `${name}.svg`), 'utf8');
                const body = svg.replace(/<!--[\s\S]*?-->/g, '').replace(/^[\s\S]*?<svg[^>]*>|<\/svg>[\s\S]*$/g, '').replace(/\s*\n\s*/g, '').trim();
                return `<symbol id="${name}" viewBox="0 0 24 24">${body}</symbol>`;
            });
            fs.mkdirSync(path.dirname(output), { recursive: true });
            fs.writeFileSync(output, `<!-- Lucide icons (https://lucide.dev), ISC License. Generated by vite.config.js -->\n<svg xmlns="http://www.w3.org/2000/svg">\n${symbols.join('\n')}\n</svg>\n`);
            console.log(`Lucide sprite: ${symbols.length} icons written to ${path.relative(__dirname, output)}`);
        }
    };
}

