import { Component, OnInit, inject } from '@angular/core';
import { takeUntilDestroyed } from '@angular/core/rxjs-interop';
import { RouterLink } from '@angular/router';
import { LucideChevronRight, LucideLock, LucidePlus, LucideTags } from '@lucide/angular';
import { TranslatePipe } from '@ngx-translate/core';
import { AuthService } from 'src/app/core/services/auth.service';
import { ClaimTypeInfo, IdentityApiService } from 'src/app/core/services/identity-api.service';
import { BoolIconComponent } from 'src/app/ui/badges/badges';
import { EmptyStateComponent } from 'src/app/ui/list/empty-state.component';
import { ListState, toApiSort, toBool } from 'src/app/ui/list/list-state';
import { PaginationComponent } from 'src/app/ui/list/pagination.component';
import { RefreshBus } from 'src/app/ui/list/refresh-bus';
import { SearchInputComponent } from 'src/app/ui/list/search-input.component';
import { SortHeaderComponent } from 'src/app/ui/list/sort-header.component';
import { PageHeaderComponent } from 'src/app/ui/page-header/page-header.component';
import { SidePaneService } from 'src/app/ui/side-pane/side-pane';

export const CLAIM_TYPES_REFRESH = 'claim-types';

/** Claim types list. Creating and editing happen in the side pane. */
@Component({
  selector: 'app-claim-types',
  imports: [
    RouterLink, PageHeaderComponent, EmptyStateComponent, PaginationComponent, SearchInputComponent, SortHeaderComponent, BoolIconComponent,
    LucideChevronRight, LucideLock, LucidePlus, LucideTags, TranslatePipe
  ],
  template: `
    <app-page-header [title]="'Routes.ClaimTypes' | translate" [subtitle]="'ClaimTypes.List.Subtitle' | translate" [count]="list.total()">
      @if (canEdit) {
        <div actions>
          <a class="btn btn-primary btn-sm" [routerLink]="pane.link('claim-type-add')"><svg lucidePlus class="size-4"></svg>{{ 'ClaimTypes.New' | translate }}</a>
        </div>
      }
    </app-page-header>

    <div class="mb-3 flex flex-col gap-2 sm:flex-row sm:items-center">
      <app-search-input class="sm:w-72" [value]="list.search()" [placeholder]="'ClaimTypes.List.SearchPlaceholder' | translate" (search)="list.setSearch($event)" />
      <select class="select select-sm sm:w-44" [attr.aria-label]="'Common.Required' | translate" [value]="list.params()['required'] ?? ''"
        (change)="list.setParams({ required: $any($event.target).value })">
        <option value="">{{ 'ClaimTypes.List.RequiredAny' | translate }}</option>
        <option value="true">{{ 'ClaimTypes.List.RequiredOnly' | translate }}</option>
        <option value="false">{{ 'ClaimTypes.List.OptionalOnly' | translate }}</option>
      </select>
      <select class="select select-sm sm:w-48" [attr.aria-label]="'ClaimTypes.List.AutoGenerated' | translate" [value]="list.params()['autoGenerated'] ?? ''"
        (change)="list.setParams({ autoGenerated: $any($event.target).value })">
        <option value="">{{ 'ClaimTypes.List.OriginAny' | translate }}</option>
        <option value="true">{{ 'ClaimTypes.List.AutoGenerated' | translate }}</option>
        <option value="false">{{ 'ClaimTypes.List.ManuallyCreated' | translate }}</option>
      </select>
      @if (list.hasFilters()) {
        <button type="button" class="btn btn-ghost btn-sm" (click)="list.clearFilters()">{{ 'ClaimTypes.List.ClearFilters' | translate }}</button>
      }
    </div>

    <div class="panel overflow-x-auto">
      <table class="table">
        <thead>
          <tr>
            <th app-sort-header [list]="list" field="name">{{ 'Common.Name' | translate }}</th>
            <th app-sort-header [list]="list" field="displayName">{{ 'Common.DisplayName' | translate }}</th>
            <th app-sort-header [list]="list" field="valueType">{{ 'ClaimTypes.Fields.ValueType' | translate }}</th>
            <th app-sort-header class="text-center" [list]="list" field="userEditable">{{ 'ClaimTypes.Fields.UserEditable' | translate }}</th>
            <th app-sort-header class="text-center" [list]="list" field="required">{{ 'Common.Required' | translate }}</th>
            <th class="w-12"><span class="sr-only">{{ 'ClaimTypes.List.Open' | translate }}</span></th>
          </tr>
        </thead>
        <tbody>
          @if (list.loading() && !list.items()?.length) {
            @for (row of [1, 2, 3, 4]; track row) {
              <tr><td colspan="6"><div class="skeleton h-4 w-full"></div></td></tr>
            }
          } @else {
            @for (claim of list.items(); track claim.id) {
              <tr class="hover:bg-base-200/60" [class.opacity-60]="list.loading()">
                <td>
                  <a class="inline-flex items-center gap-1.5 font-mono text-sm font-semibold hover:text-primary" [routerLink]="pane.link(['claim-type', claim.id!])">
                    {{ claim.name }}
                    @if (claim.reserved) { <svg lucideLock class="size-3.5 text-warning" [attr.aria-label]="'Common.Reserved' | translate"></svg> }
                  </a>
                  @if (claim.description) { <p class="line-clamp-1 max-w-md text-xs text-base-content/60">{{ claim.description }}</p> }
                </td>
                <td>{{ claim.displayName || '—' }}</td>
                <td><span class="badge badge-sm badge-ghost">{{ claim.valueType || 'String' }}</span></td>
                <td class="text-center"><app-bool-icon [value]="claim.userEditable" /></td>
                <td class="text-center"><app-bool-icon [value]="claim.required" /></td>
                <td class="text-right">
                  <a class="btn btn-ghost btn-xs btn-square" [routerLink]="pane.link(['claim-type', claim.id!])" [attr.aria-label]="'ClaimTypes.List.OpenItem' | translate: { name: claim.name }">
                    <svg lucideChevronRight class="size-4"></svg>
                  </a>
                </td>
              </tr>
            } @empty {
              <tr>
                <td colspan="6">
                  <app-empty-state [title]="(list.hasFilters() ? 'ClaimTypes.List.NoMatches' : 'ClaimTypes.List.Empty') | translate"
                    [message]="(list.hasFilters() ? 'ClaimTypes.List.NoMatchesHint' : 'ClaimTypes.List.EmptyHint') | translate">
                    <svg icon lucideTags class="size-5"></svg>
                    @if (canEdit && !list.hasFilters()) {
                      <a actions class="btn btn-sm" [routerLink]="pane.link('claim-type-add')"><svg lucidePlus class="size-4"></svg>{{ 'ClaimTypes.New' | translate }}</a>
                    }
                  </app-empty-state>
                </td>
              </tr>
            }
          }
        </tbody>
      </table>
      @if (list.count() > 0) {
        <app-pagination class="border-t border-base-300 px-4 py-3" [page]="list.page()" [pageSize]="list.pageSize()" [count]="list.count()"
          (pageChange)="list.setPage($event)" (pageSizeChange)="list.setPageSize($event)" />
      }
    </div>
  `
})
export class ClaimTypesComponent implements OnInit {
  private readonly _api = inject(IdentityApiService);
  private readonly _auth = inject(AuthService);
  protected readonly pane = inject(SidePaneService);
  protected readonly canEdit = this._auth.isAdminUIUsersWriter() || this._auth.isAdminUIClientsWriter();

  protected readonly list = new ListState<ClaimTypeInfo>({
    sort: 'name',
    dir: 'asc',
    params: ['required', 'autoGenerated'],
    load: query => this._api.getClaimTypes(query.page, query.pageSize, toApiSort(query), query.search || undefined,
      toBool(query.params['required']), toBool(query.params['autoGenerated']))
  });

  constructor() {
    inject(RefreshBus).on(CLAIM_TYPES_REFRESH).pipe(takeUntilDestroyed()).subscribe(() => this.list.refresh());
  }

  public ngOnInit(): void {
    this.list.start();
  }
}
