import { ValidatorFn, Validators } from '@angular/forms';
import { ClaimInfo, ClaimTypeInfo, MfaPolicy, PasswordExpirationPolicy } from 'src/app/core/services/identity-api.service';
import { StatusTone } from 'src/app/ui/badges/badges';

/** Claims that are managed through dedicated user fields and should not be added as additional details. */
export const DISCOURAGED_CLAIMS = ['sub', 'email', 'email_verified', 'phone_number', 'phone_number_verified', 'name'];

export const MFA_POLICIES = Object.values(MfaPolicy);
export const PASSWORD_EXPIRATION_POLICIES = Object.values(PasswordExpirationPolicy);

/** Claim types an administrator may add as additional details. */
export function isAssignableClaimType(type: ClaimTypeInfo): boolean {
  return type.required !== true && type.autoGenerated !== true && !DISCOURAGED_CLAIMS.includes(type.name ?? '');
}

/** `given_name family_name` from the user's claims, if present. */
export function nameFromClaims(claims: ClaimInfo[] | undefined): string {
  const given = claims?.find(c => c.type === 'given_name')?.value ?? '';
  const family = claims?.find(c => c.type === 'family_name')?.value ?? '';
  return `${given} ${family}`.trim();
}

/** Validators for a claim value of the given type: required plus the type's regular expression rule. */
export function claimValueValidators(type: ClaimTypeInfo | undefined): ValidatorFn[] {
  return [Validators.required, ...(type?.rule ? [Validators.pattern(type.rule)] : [])];
}

/** Date claims are stored as `MM-dd-yyyy` (the format the previous UI wrote); converts to the `yyyy-MM-dd` of date inputs. */
export function claimDateToInput(value: string | null | undefined): string {
  if (!value) {
    return '';
  }
  const legacy = /^(\d{1,2})-(\d{1,2})-(\d{4})$/.exec(value.trim());
  if (legacy) {
    return `${legacy[3]}-${legacy[1].padStart(2, '0')}-${legacy[2].padStart(2, '0')}`;
  }
  const iso = /^(\d{4})-(\d{2})-(\d{2})/.exec(value.trim());
  return iso ? `${iso[1]}-${iso[2]}-${iso[3]}` : '';
}

/** Converts a date input value (`yyyy-MM-dd`) to the stored claim format (`MM-dd-yyyy`). */
export function inputDateToClaim(value: string | null | undefined): string {
  const iso = /^(\d{4})-(\d{2})-(\d{2})$/.exec(value ?? '');
  return iso ? `${iso[2]}-${iso[3]}-${iso[1]}` : '';
}

